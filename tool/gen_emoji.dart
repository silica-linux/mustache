// Generates lib/src/emoji_table.g.dart, the emoji of the folder emoji picker, from the Unicode
// emoji data and the CLDR annotations (names and search keywords in English and Italian).
//
//   dart run tool/gen_emoji.dart <emoji-test.txt> <cldr-annotations-dir> [--max-version=16.0]
//
// <cldr-annotations-dir> holds annotations-en.xml, annotationsDerived-en.xml and the same for
// `it`, copied from `common/annotations` and `common/annotationsDerived` of the CLDR
// repository. Only fully-qualified emoji are kept, without skin-tone variants (the base
// emoji stands for them), and only those introduced up to `--max-version` (the newest emoji
// the colour emoji font of the image draws; the others would show as empty boxes).
//
// The table is one raw string, one emoji per line, fields separated by a tab:
//   emoji, English name, English keywords, Italian name, Italian keywords (keywords by `|`),
// under `#<group>` lines. Unicode data and CLDR: Unicode License v3 (unicode.org/license).

import 'dart:io';

const groups = {
  'Smileys & Emotion': 'smileys',
  'People & Body': 'smileys',
  'Animals & Nature': 'animals',
  'Food & Drink': 'food',
  'Activities': 'activity',
  'Travel & Places': 'travel',
  'Objects': 'objects',
  'Symbols': 'symbols',
  'Flags': 'flags',
};

const order = [
  'smileys',
  'animals',
  'food',
  'activity',
  'travel',
  'objects',
  'symbols',
  'flags',
];

String unescape(String s) => s
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&amp;', '&');

String clean(String s) =>
    unescape(s).replaceAll('\t', ' ').replaceAll('\n', ' ').trim();

/// cp -> (name, keywords) of one language from its two annotation files.
Map<String, (String, String)> annotations(String dir, String lang) {
  final names = <String, String>{};
  final words = <String, String>{};
  final tag = RegExp(
    r'<annotation cp="([^"]+)"( type="tts")?>([^<]*)</annotation>',
  );
  for (final file in ['annotations', 'annotationsDerived']) {
    final text = File('$dir/$file-$lang.xml').readAsStringSync();
    for (final m in tag.allMatches(text)) {
      final cp = unescape(m.group(1)!);
      final value = clean(m.group(3)!);
      if (m.group(2) != null) {
        names[cp] = value;
      } else {
        words[cp] = value.split(RegExp(r'\s*\|\s*')).join('|');
      }
    }
  }
  return {for (final cp in names.keys) cp: (names[cp]!, words[cp] ?? '')};
}

(String, String) lookup(Map<String, (String, String)> from, String emoji) =>
    from[emoji] ??
    from[emoji.replaceAll('️', '')] ??
    from['$emoji️'] ??
    ('', '');

void main(List<String> args) {
  final positional = [
    for (final a in args)
      if (!a.startsWith('--')) a,
  ];
  if (positional.length != 2) {
    stderr.writeln(
      'usage: dart run tool/gen_emoji.dart <emoji-test.txt> <annotations-dir> '
      '[--max-version=16.0]',
    );
    exit(64);
  }
  final maxVersion = double.parse(
    args
        .firstWhere(
          (a) => a.startsWith('--max-version='),
          orElse: () => '--max-version=16.0',
        )
        .split('=')
        .last,
  );
  final en = annotations(positional[1], 'en');
  final it = annotations(positional[1], 'it');
  final byGroup = {for (final g in order) g: <String>[]};
  var group = '';
  final line = RegExp(
    r'^([0-9A-F ]+?)\s*;\s*fully-qualified\s*# (\S+) E(\d+\.\d+) (.*)$',
  );
  var kept = 0;
  for (final raw in File(positional[0]).readAsLinesSync()) {
    if (raw.startsWith('# group: ')) {
      group = raw.substring(9).trim();
      continue;
    }
    final m = line.firstMatch(raw);
    final id = groups[group];
    if (m == null || id == null) continue;
    final points = [
      for (final h in m.group(1)!.trim().split(' ')) int.parse(h, radix: 16),
    ];
    // Skin-tone variants: the base emoji stands for them.
    if (points.any((p) => p >= 0x1F3FB && p <= 0x1F3FF)) continue;
    if (double.parse(m.group(3)!) > maxVersion) continue;
    final emoji = String.fromCharCodes(points);
    final (enName, enWords) = lookup(en, emoji);
    final (itName, itWords) = lookup(it, emoji);
    final name = enName.isEmpty ? clean(m.group(4)!) : enName;
    byGroup[id]!.add(
      [
        emoji,
        name.toLowerCase(),
        enWords.toLowerCase(),
        itName.toLowerCase(),
        itWords.toLowerCase(),
      ].join('\t'),
    );
    kept++;
  }
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_emoji.dart from the Unicode emoji data and the CLDR',
    )
    ..writeln(
      '// annotations (Unicode License v3, https://www.unicode.org/license.txt). Do not edit.',
    )
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln(
      '/// $kept emoji up to Emoji $maxVersion, by group; see emoji_data.dart.',
    )
    ..writeln("const String emojiTable = r'''");
  for (final g in order) {
    out.writeln('#$g');
    for (final l in byGroup[g]!) {
      out.writeln(l);
    }
  }
  out.writeln("''';");
  File('lib/src/emoji_table.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote lib/src/emoji_table.g.dart: $kept emoji');
}
